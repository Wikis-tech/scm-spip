-- SCM SPIP Phase 6D - Final AI runtime repair
-- RUN ONLY IN THE SCM SPIP SUPABASE PROJECT.
-- Idempotent: repairs missing Copilot persistence, storage, provider-health objects.

begin;

create extension if not exists pgcrypto;

create table if not exists public.spip_ai_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  workspace_id text,
  title text not null default 'New AI conversation',
  mode text not null default 'assistant' check (mode in ('assistant','research','proposal','email','meeting','followup','analysis')),
  data_classification text not null default 'INTERNAL' check (data_classification in ('PUBLIC','INTERNAL','CONFIDENTIAL')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.spip_ai_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.spip_ai_conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('user','assistant','system')),
  content text not null,
  provider text,
  model text,
  citations jsonb not null default '[]'::jsonb,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  latency_ms integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.spip_ai_documents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  workspace_id text,
  conversation_id uuid references public.spip_ai_conversations(id) on delete set null,
  filename text not null,
  mime_type text not null,
  storage_path text,
  byte_size bigint not null default 0,
  sha256 text,
  extracted_text text,
  extraction_status text not null default 'READY' check (extraction_status in ('PENDING','READY','FAILED')),
  created_at timestamptz not null default now()
);

create table if not exists public.spip_ai_artifacts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  workspace_id text,
  conversation_id uuid references public.spip_ai_conversations(id) on delete set null,
  artifact_type text not null check (artifact_type in ('pdf','docx','pptx','xlsx','txt')),
  title text not null,
  storage_path text not null,
  mime_type text not null,
  byte_size bigint not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.spip_ai_provider_health (
  provider text primary key,
  status text not null default 'UNKNOWN' check (status in ('UNKNOWN','HEALTHY','COOLDOWN','DISABLED')),
  cooldown_until timestamptz,
  consecutive_failures integer not null default 0,
  last_error_code text,
  last_success_at timestamptz,
  last_failure_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.spip_ai_usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  conversation_id uuid references public.spip_ai_conversations(id) on delete set null,
  provider text,
  model text,
  task_type text,
  status text not null,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  latency_ms integer not null default 0,
  error_code text,
  created_at timestamptz not null default now()
);

create index if not exists idx_spip_ai_conversations_user_updated on public.spip_ai_conversations(user_id, updated_at desc);
create index if not exists idx_spip_ai_messages_conversation_created on public.spip_ai_messages(conversation_id, created_at asc);
create index if not exists idx_spip_ai_documents_user_workspace on public.spip_ai_documents(user_id, workspace_id, created_at desc);
create index if not exists idx_spip_ai_artifacts_user_created on public.spip_ai_artifacts(user_id, created_at desc);
create index if not exists idx_spip_ai_usage_user_created on public.spip_ai_usage_events(user_id, created_at desc);

alter table public.spip_ai_conversations enable row level security;
alter table public.spip_ai_messages enable row level security;
alter table public.spip_ai_documents enable row level security;
alter table public.spip_ai_artifacts enable row level security;
alter table public.spip_ai_provider_health enable row level security;
alter table public.spip_ai_usage_events enable row level security;

revoke all on table public.spip_ai_conversations from anon, authenticated;
revoke all on table public.spip_ai_messages from anon, authenticated;
revoke all on table public.spip_ai_documents from anon, authenticated;
revoke all on table public.spip_ai_artifacts from anon, authenticated;
revoke all on table public.spip_ai_provider_health from anon, authenticated;
revoke all on table public.spip_ai_usage_events from anon, authenticated;

grant all on table public.spip_ai_conversations to service_role;
grant all on table public.spip_ai_messages to service_role;
grant all on table public.spip_ai_documents to service_role;
grant all on table public.spip_ai_artifacts to service_role;
grant all on table public.spip_ai_provider_health to service_role;
grant all on table public.spip_ai_usage_events to service_role;

do $$
begin
  if not exists (select 1 from storage.buckets where id = 'spip-ai-private') then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values (
      'spip-ai-private',
      'spip-ai-private',
      false,
      20971520,
      array[
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'application/pdf',
        'text/plain',
        'text/csv',
        'text/markdown',
        'application/json'
      ]
    );
  else
    update storage.buckets
      set public = false,
          file_size_limit = greatest(coalesce(file_size_limit, 0), 20971520)
    where id = 'spip-ai-private';
  end if;
end $$;

insert into public.spip_ai_provider_health(provider, status, updated_at)
values
  ('groq','UNKNOWN',now()),
  ('cerebras','UNKNOWN',now()),
  ('openrouter','UNKNOWN',now()),
  ('cloudflare','UNKNOWN',now())
on conflict (provider) do nothing;

commit;

